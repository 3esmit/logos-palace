QJsonObject indexerTransaction(
    const palace::PalaceLezTransactionPlanV3& plan,
    const std::string& transactionHash)
{
    palace::PalaceLezBytes32 programId{};
    LOGOS_ASSERT_TRUE(palace::PalaceLezCodec::parseBytes32Hex(
        plan.programIdHex,
        programId));
    QJsonObject message;
    message.insert(
        QStringLiteral("program_id"),
        QString::fromStdString(palace::PalaceLezCodec::accountIdBase58(programId)));
    QJsonArray accounts;
    QJsonArray nonces;
    for (const std::string& accountHex : plan.accountIdsHex) {
        palace::PalaceLezBytes32 account{};
        LOGOS_ASSERT_TRUE(palace::PalaceLezCodec::parseBytes32Hex(accountHex, account));
        accounts.append(
            QString::fromStdString(palace::PalaceLezCodec::accountIdBase58(account)));
        nonces.append(0);
    }
    message.insert(QStringLiteral("account_ids"), accounts);
    message.insert(QStringLiteral("nonces"), nonces);
    QJsonArray words;
    for (const std::uint32_t word : plan.instructionWords)
        words.append(static_cast<double>(word));
    message.insert(QStringLiteral("instruction_data"), words);

    QJsonArray signatures;
    for (const bool required : plan.signingRequirements) {
        if (!required)
            continue;
        QJsonArray pair;
        pair.append(QString(128U, QLatin1Char('1')));
        pair.append(QString::fromLatin1(QByteArray(32, '\x01').toBase64()));
        signatures.append(pair);
    }
    QJsonObject witness;
    witness.insert(QStringLiteral("signatures_and_public_keys"), signatures);
    witness.insert(QStringLiteral("proof"), QJsonValue::Null);

    QJsonObject transaction;
    transaction.insert(QStringLiteral("hash"), QString::fromStdString(transactionHash));
    transaction.insert(QStringLiteral("message"), message);
    transaction.insert(QStringLiteral("witness_set"), witness);
    QJsonObject tagged;
    tagged.insert(QStringLiteral("Public"), transaction);
    return tagged;
}

std::string indexerJson(
    const std::vector<std::pair<palace::PalaceLezTransactionPlanV3, std::string>>& values)
{
    QJsonArray transactions;
    for (const auto& value : values)
        transactions.append(indexerTransaction(value.first, value.second));
    return QJsonDocument(transactions).toJson(QJsonDocument::Compact).toStdString();
}

std::string indexerRpcJson(
    const std::vector<std::pair<palace::PalaceLezTransactionPlanV3, std::string>>& values)
{
    QJsonArray transactions;
    for (const auto& value : values)
        transactions.append(indexerTransaction(value.first, value.second));
    QJsonObject envelope;
    envelope.insert(QStringLiteral("jsonrpc"), QStringLiteral("2.0"));
    envelope.insert(QStringLiteral("result"), transactions);
    envelope.insert(QStringLiteral("id"), 1);
    return QJsonDocument(envelope).toJson(QJsonDocument::Compact).toStdString();
}

