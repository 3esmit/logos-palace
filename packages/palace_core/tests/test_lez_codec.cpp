    const std::vector<PalaceLezInstructionV3> instructions = allInstructions();
    std::vector<std::pair<PalaceLezTransactionPlanV3, std::string>> indexed;
    for (std::size_t index = 0; index < instructions.size(); ++index) {
        indexed.push_back(
            {PalaceLezCodec::buildTransaction(kProgramId, kSigner, instructions[index]),
             hash(index)});
        LOGOS_ASSERT_TRUE(indexed.back().first.accepted);
    }
    const PalaceLezRebuildResultV3 rebuilt =
        PalaceLezCodec::rebuildFinalizedHistory(
            kProgramId,
            kRootPda,
            indexerJson(indexed));
