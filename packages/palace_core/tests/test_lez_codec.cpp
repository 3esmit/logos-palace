std::string hash(const std::size_t ordinal)
{
    std::ostringstream stream;
    stream << std::hex << std::setfill('0') << std::setw(64) << ordinal + 1U;
    return stream.str();
}

std::vector<std::uint8_t> wordsLeBytes(const std::vector<std::uint32_t>& words)
{
    std::vector<std::uint8_t> output;
    output.reserve(words.size() * sizeof(std::uint32_t));
    for (const std::uint32_t word : words) {
        output.push_back(static_cast<std::uint8_t>(word & 0xffU));
        output.push_back(static_cast<std::uint8_t>((word >> 8U) & 0xffU));
        output.push_back(static_cast<std::uint8_t>((word >> 16U) & 0xffU));
        output.push_back(static_cast<std::uint8_t>((word >> 24U) & 0xffU));
    }
    return output;
}

std::string hexBytes(const std::vector<std::uint8_t>& bytes)
{
    static constexpr char digits[] = "0123456789abcdef";
    std::string output(bytes.size() * 2U, '0');
    for (std::size_t index = 0U; index < bytes.size(); ++index) {
        output[index * 2U] = digits[bytes[index] >> 4U];
        output[index * 2U + 1U] = digits[bytes[index] & 0x0fU];
    }
    return output;
}

std::vector<std::uint8_t> accountIdBytes(const std::vector<std::string>& accountIdsHex)
{
    std::vector<std::uint8_t> output;
    output.reserve(accountIdsHex.size() * 32U);
    for (const std::string& accountIdHex : accountIdsHex) {
        palace::PalaceLezBytes32 account{};
        if (!palace::PalaceLezCodec::parseBytes32Hex(accountIdHex, account))
            return {};
        output.insert(output.end(), account.begin(), account.end());
    }
    return output;
}

